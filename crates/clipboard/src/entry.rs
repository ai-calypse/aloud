//! What the history holds, and the pure rules about it: what is never stored,
//! how a copy is recognised as one already seen, and what can be done with it.

use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub enum ClipboardKind {
    Text,
    Image,
    Files,
}

impl ClipboardKind {
    pub(crate) fn tag(self) -> &'static str {
        match self {
            ClipboardKind::Text => "text",
            ClipboardKind::Image => "image",
            ClipboardKind::Files => "files",
        }
    }

    pub(crate) fn from_tag(tag: &str) -> ClipboardKind {
        match tag {
            "image" => ClipboardKind::Image,
            "files" => ClipboardKind::Files,
            _ => ClipboardKind::Text,
        }
    }
}

/// One thing the user copied, as the panel lists it. The full text and the
/// image's pixels stay in Rust: the row needs a preview, and an action names
/// the entry by id.
#[derive(Debug, Clone, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct ClipboardEntry {
    pub id: u32,
    pub kind: ClipboardKind,
    /// First line or so of text, the file names, or "Image · 1200×800".
    pub preview: String,
    /// A small `data:` PNG for images; the CSP loads nothing else.
    pub thumbnail: Option<String>,
    pub pinned: bool,
    /// Unix seconds of the most recent copy of this content.
    pub copied_at: u32,
    pub actions: Vec<SmartAction>,
}

/// Something worth doing with an entry, offered as a button on its row.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, specta::Type)]
#[serde(rename_all = "camelCase")]
pub struct SmartAction {
    pub id: String,
    pub label: String,
}

fn action(id: &str, label: &str) -> SmartAction {
    SmartAction {
        id: id.into(),
        label: label.into(),
    }
}

/// A fresh copy, before it is stored.
#[derive(Debug, Clone)]
pub enum Captured {
    Text(String),
    Image {
        width: usize,
        height: usize,
        rgba: Vec<u8>,
    },
    Files(Vec<String>),
}

/// Pasteboard types that mean "do not keep this". Password managers set the
/// first four on a copied password so clipboard tools skip it; storing one
/// would put a secret on disk that its owner deliberately kept transient.
const NEVER_STORE: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "de.petermaurer.TransientPasteboardType",
    "com.agilebits.onepassword",
    "net.antelle.keeweb",
    "com.typeit4me.clipping",
];

/// Whether a copy carrying these types must not be recorded.
pub fn is_concealed(types: &[String]) -> bool {
    types.iter().any(|t| NEVER_STORE.contains(&t.as_str()))
}

/// A stable 64-bit FNV-1a over `parts`, in hex. The hash is persisted as the
/// dedupe key, so it cannot be `DefaultHasher`, whose output may change with
/// the compiler. Not a security hash — a collision merely merges two entries.
pub fn content_hash(kind: ClipboardKind, parts: &[&[u8]]) -> String {
    let mut hash: u64 = 0xcbf2_9ce4_8422_2325;
    let mut feed = |bytes: &[u8]| {
        for b in bytes {
            hash ^= u64::from(*b);
            hash = hash.wrapping_mul(0x0100_0000_01b3);
        }
        // A separator, so ("ab","c") and ("a","bc") differ.
        hash ^= 0xff;
        hash = hash.wrapping_mul(0x0100_0000_01b3);
    };
    feed(kind.tag().as_bytes());
    for part in parts {
        feed(part);
    }
    format!("{hash:016x}")
}

pub(crate) fn is_url(text: &str) -> bool {
    let t = text.trim();
    (t.starts_with("http://") || t.starts_with("https://"))
        && !t.contains(char::is_whitespace)
        && t.len() > 8
}

pub(crate) fn is_email(text: &str) -> bool {
    let t = text.trim();
    let Some((user, domain)) = t.split_once('@') else {
        return false;
    };
    !user.is_empty()
        && !t.contains(char::is_whitespace)
        && !domain.contains('@')
        && domain.contains('.')
        && !domain.starts_with('.')
        && !domain.ends_with('.')
}

fn is_json(text: &str) -> bool {
    let t = text.trim();
    (t.starts_with('{') || t.starts_with('['))
        && serde_json::from_str::<serde_json::Value>(t).is_ok()
}

/// The actions a text copy earns, by what it looks like.
pub fn text_actions(text: &str) -> Vec<SmartAction> {
    let mut out = Vec::new();
    if is_url(text) {
        out.push(action("open-url", "Open link"));
    }
    if is_email(text) {
        out.push(action("compose-email", "Write email"));
    }
    if is_json(text) {
        out.push(action("format-json", "Format JSON"));
        out.push(action("minify-json", "Minify JSON"));
    }
    if let Some(rgb) = crate::colors::parse(text) {
        out.push(action("color-hex", &format!("Copy {}", rgb.hex())));
        out.push(action("color-rgb", &format!("Copy {}", rgb.css())));
    }
    if text != text.trim() {
        out.push(action("trim", "Copy trimmed"));
    }
    out
}

/// Pretty or minified JSON, or None when it is not JSON.
pub fn reformat_json(text: &str, pretty: bool) -> Option<String> {
    let value: serde_json::Value = serde_json::from_str(text.trim()).ok()?;
    if pretty {
        serde_json::to_string_pretty(&value).ok()
    } else {
        serde_json::to_string(&value).ok()
    }
}

pub(crate) fn file_actions() -> Vec<SmartAction> {
    vec![
        action("reveal", "Show in Finder"),
        action("copy-paths", "Copy paths"),
    ]
}

pub(crate) fn image_actions() -> Vec<SmartAction> {
    if cfg!(target_os = "macos") {
        vec![action("ocr", "Copy text in image")]
    } else {
        Vec::new()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn types(names: &[&str]) -> Vec<String> {
        names.iter().map(|s| (*s).to_string()).collect()
    }

    #[test]
    fn a_password_managers_copy_is_never_stored() {
        // The regression this guards: a 1Password copy carries plain text next
        // to its concealed marker, so "has text" alone would have stored it.
        assert!(is_concealed(&types(&[
            "public.utf8-plain-text",
            "org.nspasteboard.ConcealedType"
        ])));
        assert!(is_concealed(&types(&["com.agilebits.onepassword"])));
        assert!(!is_concealed(&types(&[
            "public.utf8-plain-text",
            "public.html"
        ])));
        assert!(!is_concealed(&[]));
    }

    #[test]
    fn hash_is_stable_and_separates_parts_and_kinds() {
        assert_eq!(
            content_hash(ClipboardKind::Text, &[b"hello"]),
            content_hash(ClipboardKind::Text, &[b"hello"])
        );
        assert_ne!(
            content_hash(ClipboardKind::Text, &[b"ab", b"c"]),
            content_hash(ClipboardKind::Text, &[b"a", b"bc"])
        );
        assert_ne!(
            content_hash(ClipboardKind::Text, &[b"x"]),
            content_hash(ClipboardKind::Files, &[b"x"])
        );
        // Pinned so a compiler upgrade cannot orphan every stored entry.
        assert_eq!(
            content_hash(ClipboardKind::Text, &[b"hello"]),
            "1967afffbe7ff64a"
        );
    }

    #[test]
    fn smart_actions_follow_what_the_text_is() {
        let ids = |t: &str| -> Vec<String> { text_actions(t).into_iter().map(|a| a.id).collect() };
        assert_eq!(ids("https://example.com/a?b=1"), ["open-url"]);
        assert!(
            ids("see https://example.com").is_empty(),
            "prose with a link is not a link"
        );
        assert_eq!(ids("a@b.co"), ["compose-email"]);
        assert!(ids("a@b").is_empty());
        assert_eq!(ids("{\"a\":1}"), ["format-json", "minify-json"]);
        assert!(ids("{not json").is_empty());
        assert_eq!(ids("#ff8800"), ["color-hex", "color-rgb"]);
        assert_eq!(ids("  padded "), ["trim"]);
    }

    #[test]
    fn json_round_trips_through_both_forms() {
        let pretty = reformat_json("{\"a\":[1,2]}", true).unwrap();
        assert!(pretty.contains('\n'));
        assert_eq!(reformat_json(&pretty, false).unwrap(), "{\"a\":[1,2]}");
        assert!(reformat_json("nope", true).is_none());
    }
}
