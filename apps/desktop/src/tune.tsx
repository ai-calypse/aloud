/**
 * The motion tuner. Dev-only: not a Tauri window, not a build input, served
 * only by `vite` in dev.
 *
 *     cd apps/desktop && pnpm exec vite --port 5199
 *     open http://localhost:5199/tune.html
 *
 * Frames the *real* overlay in an iframe, writes candidate motion.css tokens
 * onto its document, and drives it through states otherwise only reachable by
 * holding a key and speaking. Out comes a block of CSS to paste into
 * motion.css, its `linear()` curves regenerated by the same solver that
 * produced the shipped ones (lib/spring-curve.ts, pinned by a test).
 */

